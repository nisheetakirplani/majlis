// Turns the Figma token export in tokens/ into CSS variables (build/css/) and a
// Tailwind theme. Run with `npm run tokens`.
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';
import StyleDictionary from 'style-dictionary';

const BRANDS = readdirSync('tokens/brands').filter((f) => f.endsWith('.json')).map((f) => f.replace('.json', ''));
const DEFAULT_BRAND = 'majlis';

const figma = (token) => (token.$extensions ?? token.original?.$extensions ?? {})['com.figma'] ?? {};

const hooks = {
  transforms: {
    // Use the CSS variable name Figma shows in Dev Mode, so design and code share names.
    'name/figma-code-syntax': {
      type: 'name',
      transform: (token) => {
        const web = figma(token).codeSyntax?.WEB;
        return web ? web.replace(/^var\(--/, '').replace(/\)$/, '') : token.path.join('-');
      },
    },
    'value/font-family-css': {
      type: 'value',
      filter: (token) => token.$type === 'fontFamily',
      transform: (token) => `"${token.$value}", ${/mono/i.test(token.$value) ? 'monospace' : 'sans-serif'}`,
    },
  },
};
const transforms = ['name/figma-code-syntax', 'value/font-family-css'];

async function buildCss({ include = [], source, destination, selector }) {
  const sd = new StyleDictionary({
    hooks,
    include,
    source,
    log: { verbosity: 'silent', warnings: 'disabled' },
    platforms: {
      css: {
        transforms,
        buildPath: 'build/css/',
        files: [{
          destination,
          format: 'css/variables',
          filter: (token) => token.isSource,
          options: { selector, outputReferences: true },
        }],
      },
    },
  });
  await sd.buildAllPlatforms();
  console.log(`  build/css/${destination}`);
}

console.log('Building CSS variables');
await buildCss({ source: ['tokens/primitives.json'], destination: 'primitives.css', selector: ':root' });
for (const brand of BRANDS) {
  await buildCss({
    include: ['tokens/primitives.json'],
    source: [`tokens/brands/${brand}.json`],
    destination: `brands/${brand}.css`,
    selector: brand === DEFAULT_BRAND ? `:root, [data-brand="${brand}"]` : `[data-brand="${brand}"]`,
  });
}
// Semantic tokens are re-declared on every [data-brand] element so a brand can be
// switched on any container, not only on <html>.
await buildCss({
  include: ['tokens/primitives.json', `tokens/brands/${DEFAULT_BRAND}.json`],
  source: ['tokens/semantic/*.json'],
  destination: 'semantic.css',
  selector: ':root, [data-brand]',
});
await buildCss({
  include: ['tokens/primitives.json', `tokens/brands/${DEFAULT_BRAND}.json`, 'tokens/semantic/*.json'],
  source: ['tokens/executive-dashboard/light.json'],
  destination: 'dashboard-light.css',
  selector: ':root, [data-brand]',
});
await buildCss({
  include: ['tokens/primitives.json', `tokens/brands/${DEFAULT_BRAND}.json`, 'tokens/semantic/*.json'],
  source: ['tokens/executive-dashboard/dark.json'],
  destination: 'dashboard-dark.css',
  selector: '[data-theme="dark"]',
});

// Tailwind theme: one utility colour per semantic colour token, e.g.
// color/action/primary/bg/default -> bg-action-primary-bg -> var(--color-action-primary-bg-default)
const cssVar = (node, path) => {
  const web = node.$extensions?.['com.figma']?.codeSyntax?.WEB;
  return web ?? `var(--${path.join('-')})`;
};
const walk = (node, path, out) => {
  if (node && typeof node === 'object' && '$value' in node) return out.push({ path, node });
  for (const [k, v] of Object.entries(node)) if (!k.startsWith('$')) walk(v, [...path, k], out);
  return out;
};
const semantic = [
  ...walk(JSON.parse(readFileSync('tokens/semantic/color.json', 'utf8')), [], []),
  ...walk(JSON.parse(readFileSync('tokens/semantic/base.json', 'utf8')), [], []),
];
const colors = new Map();
const gradients = new Map();
for (const { path, node } of semantic) {
  if (node.$type !== 'color' || path[0] !== 'color') continue;
  if (path[1] === 'gradient') {
    const stops = gradients.get(path[2]) ?? {};
    stops[path[3]] = cssVar(node, path);
    gradients.set(path[2], stops);
    continue;
  }
  const name = path.slice(1).filter((p, i, a) => !(p === 'default' && i === a.length - 1)).join('-');
  if (colors.has(name)) throw new Error(`Tailwind colour name collision: ${name}`);
  colors.set(name, cssVar(node, path));
}
const radius = semantic.filter(({ path }) => path[0] === 'radius').map(({ path, node }) => [path[1], cssVar(node, path)]);

const lines = [
  '/* Generated by build-tokens.js from tokens/semantic. Do not edit by hand. */',
  '@theme inline {',
  '  /* Only Majlis semantic colours: Tailwind\'s default palette is switched off */',
  '  --color-*: initial;',
  ...[...colors].map(([name, v]) => `  --color-${name}: ${v};`),
  '',
  '  --font-heading: var(--brand-font-heading);',
  '  --font-body: var(--brand-font-body);',
  '  --font-mono: var(--font-family-mono);',
  '',
  ...radius.map(([name, v]) => `  --radius-${name}: ${v};`),
  '}',
  '',
  ...[...gradients].map(([name, s]) => {
    const stops = ['start', 'mid', 'end'].filter((k) => s[k]).map((k) => s[k]).join(', ');
    return `@utility bg-gradient-${name} {\n  background-image: linear-gradient(120deg, ${stops});\n}`;
  }),
  '',
];
mkdirSync('build/css', { recursive: true });
writeFileSync('build/css/tailwind-theme.css', lines.join('\n'));
console.log(`  build/css/tailwind-theme.css (${colors.size} colours, ${gradients.size} gradients)`);
